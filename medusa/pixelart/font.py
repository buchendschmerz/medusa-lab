GLYPHS: dict[str, tuple[str, ...]] = _RAW


def glyph(ch: str) -> tuple[str, ...]:
    ch = ch.upper()
    return GLYPHS.get(ch, GLYPHS["?"])


def text_width(text: str, spacing: int = 1, scale: int = 1) -> int:
    if not text:
        return 0
    widths = [len(glyph(ch)[0]) for ch in text]
    return (sum(widths) + spacing * (len(widths) - 1)) * scale


def fit_text(text: str, max_width: int, spacing: int = 1, scale: int = 1) -> str:
    """Trim ``text`` (adding '..') so it fits into ``max_width`` pixels."""
    if text_width(text, spacing, scale) <= max_width:
        return text
    while text and text_width(text + "..", spacing, scale) > max_width:
        text = text[:-1]
    return (text.rstrip() + "..") if text else ""
